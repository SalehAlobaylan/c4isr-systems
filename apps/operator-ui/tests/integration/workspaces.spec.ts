import { expect, test } from './test'
import {chooseNavigation} from '../navigation'

const fixture = JSON.parse(process.env.EMAD_BROWSER_FIXTURE ?? '{}')

test('scenario to audit survives explicit run selection and public workspace switches', async ({ page }) => {
  const apiScopes: Array<Record<string, string>> = []
  const sockets: string[] = []
  await page.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.token)
  page.on('request', (r) => { if (r.url().includes('/api/v1/') && !r.url().endsWith('/auth/me')) apiScopes.push(r.headers()) })
  page.on('websocket', (ws) => sockets.push(ws.url()))
  await page.goto(`${fixture.url}/scenarios`)
  await expect(page.getByRole('heading', { name: 'Scenarios', exact: true })).toBeVisible()
  const scenarioRow = page.getByRole('heading', { name: 'restricted-area-intrusion', exact: true }).locator('../../..')
  await scenarioRow.getByRole('button', { name: 'Start run', exact: true }).click()
  const start = page.getByRole('dialog')
  await start.getByLabel('Playback speed').click()
  await page.getByRole('option', { name: '50×', exact: true }).click()
  await start.getByRole('button', { name: /Start/ }).click()
  await expect(page).toHaveURL(/\/map(?:\?|$)/)
  const context = page.getByRole('region',{name:'Workspace context'})
  await expect(context).not.toHaveAttribute('data-resource',/legacy/)
  const selected = JSON.parse((await context.getAttribute('data-resource'))!)
  const runID = selected[3]
  await expect(page.getByTestId('workspace-basis')).toContainText('Synthetic observations')
  await page.goto(`${fixture.url}/alerts`)
  await expect(page.getByText('Suspected vehicle entered Exercise area').first()).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: 'Ack', exact: true }).first().click()
  await page.getByRole('button', { name: 'New incident', exact: true }).first().click()
  const incident = page.getByRole('dialog')
  await incident.getByLabel('Title').fill('Browser compatibility exercise')
  await incident.getByRole('button', { name: 'Create incident', exact: true }).click()
  await expect(page).toHaveURL(/\/incidents\//)
  const incidentURL = page.url()
  await page.getByRole('tab', { name: 'Missions & Commands' }).click()
  await page.getByRole('button', { name: 'Plan mission', exact: true }).click()
  const mission = page.getByRole('dialog')
  await mission.getByLabel('Name').fill('Browser virtual patrol')
  await mission.locator('input[type="checkbox"]').first().check()
  await mission.getByRole('button', { name: 'Create mission', exact: true }).click()
  await page.locator('#command-asset').click()
  await page.getByRole('option', { name: /Patrol 01/ }).first().click()
  await page.locator('#command-mission').click()
  await page.getByRole('option', { name: /Browser virtual patrol/ }).click()
  await page.locator('#command-lat').fill('24.716')
  await page.locator('#command-lng').fill('46.679')
  await page.getByRole('button', { name: 'Issue command', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: 'Missions & Commands' }).getByText('COMPLETED', { exact: true }).last()).toBeVisible({ timeout: 30_000 })
  await page.goto(`${fixture.url}/timeline`)
  await expect(page.getByText('command.issued', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Public Context', exact: true }).click()
  await expect(page.getByTestId('workspace-basis')).toContainText('Public sources')
  await expect(page).toHaveURL(/\/map(?:\?|$)/)
  expect(await page.locator('body').innerText()).not.toContain('Browser compatibility exercise')
  const afterSwitch = apiScopes.length
  await page.goto(`${fixture.url}/tracks`)
  await expect(page.getByRole('row').filter({ hasText: 'PUBLIC_BROWSER_TRACK' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Scenario console' })).toHaveCount(0)
  await page.goto(incidentURL)
  await expect(page.getByText(/incident.*not found/i)).toBeVisible()
  expect(apiScopes.slice(afterSwitch).every((h) => h['x-emad-partition'] === 'PUBLIC_EVIDENCE')).toBe(true)
  await chooseNavigation(page,'Workspace environment and run',JSON.stringify(['default', 'local', 'EXERCISE_OBSERVATION', runID]))
  await expect(page.getByRole('region', { name: 'Workspace context' })).toHaveAttribute('data-resource', JSON.stringify(['default', 'local', 'EXERCISE_OBSERVATION', runID]))
  await page.goto(incidentURL)
  await expect(page.getByRole('heading', { name: 'Browser compatibility exercise' })).toBeVisible()
  expect(sockets.some((u) => u.includes(`runId=${runID}`))).toBe(true)
  expect(sockets.every((u) => !u.includes('access_token'))).toBe(true)
})

test('ordinary operator cannot receive truth and revoked identity clears the UI', async ({ page, request }) => {
  const bodies: string[] = []
  const frames: string[] = []
  await page.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.viewerToken)
  page.on('response', async (r) => { if (r.url().includes('/api/v1/')) { try { bodies.push(await r.text()) } catch {} } })
  page.on('websocket', (ws) => ws.on('framereceived', (f) => frames.push(String(f.payload))))
  await page.goto(`${fixture.url}/tracks`)
  await expect(page.getByRole('heading', { name: 'Tracks', exact: true })).toBeVisible()
  // Finish the old document before observing the new one. A late Tracks
  // response can otherwise satisfy this waiter just before navigation makes
  // its body unavailable to Chromium's network inspector.
  await page.goto('about:blank')
  const observations = page.waitForResponse((r) => r.url().includes('/api/v1/observations?') && !new URL(r.url()).searchParams.has('area') && !new URL(r.url()).searchParams.has('track_id') && r.status() === 200).then(r => r.json())
  await page.goto(`${fixture.url}/map?selected=track:missing`)
  const evidence = await observations
  expect(evidence.items.length).toBeGreaterThan(0)
  expect(evidence.items[0].id).toMatch(/^view_obs_/)
  expect(JSON.stringify(evidence)).not.toContain('PRIVATE_ACTOR_SENTINEL')
  await expect(page.getByTestId('workspace-basis')).toBeVisible()
  await expect.poll(() => frames.some((f) => f.includes('realtime.ready'))).toBe(true)
  expect((bodies.join('') + frames.join(''))).not.toContain('PRIVATE_ACTOR_SENTINEL')
  await expect(page.getByRole('button', { name: 'Public Context', exact: true })).toBeDisabled()
  await request.post(`${fixture.url}/__fixture/revoke-viewer`)
  await expect(page.getByText(/Workspace access changed/)).toBeVisible({ timeout: 10_000 })
  await expect(page.getByRole('button', { name: 'Workspace environment and run' })).toHaveCount(0)
})
