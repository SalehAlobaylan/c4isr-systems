import { readFile } from 'node:fs/promises'
import { test, expect, workspaceSelection } from './test'
const fixture = JSON.parse(process.env.EMAD_BROWSER_FIXTURE ?? '{}')
test('public moving hypothesis exposes provenance and history without control authority', async ({ page }) => {
 await page.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.token)
 await page.goto(`${fixture.url}/map`)
 await page.getByRole('button', { name: 'Public Context', exact: true }).click()
 await page.getByRole('navigation',{name:'Workspace navigation'}).getByRole('link',{name:'Systems',exact:true}).click()
 await page.getByRole('link',{name:'Explore external tracks →',exact:true}).click()
 await expect(page.getByRole('heading', { name: 'Aircraft & vessels', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Inspect aircraft claimed abcdef', exact: true }).click()
 const selected = page.getByRole('article', { name: 'Selected external hypothesis' })
 await expect(selected.getByRole('heading', { name: /aircraft.*claimed abcdef/ })).toBeVisible()
 await expect(selected.getByText('Registration country', { exact: false })).toHaveCount(0)
 await selected.getByText('Provider claims & quality fields',{exact:true}).click()
 await expect(selected.getByRole('heading', { name: 'Provider identity and classification claims' })).toBeVisible()
 await expect(selected.getByText('"affiliation": "unassessed"', { exact: false }).first()).toBeVisible()
 await expect(selected.getByText('APPLIED', { exact: true })).toHaveCount(2)
 await expect(selected.getByRole('button', { name: 'Issue command', exact: false })).toHaveCount(0)
 const download = page.waitForEvent('download')
 await selected.getByRole('button', { name: 'Download exact provider record' }).first().click()
 const raw=JSON.parse(await readFile((await (await download).path())!, 'utf8'))
 expect(raw[0]).toBe('abcdef')
 const aoi = page.getByLabel('Moving-track AOI (west,south,east,north)')
 const bounds = '39.15,21.45,39.3,21.6'
 await aoi.fill(bounds)
 await page.getByRole('button', {name: 'Filter moving tracks', exact: true}).click()
 await expect.poll(() => workspaceSelection(page.url(), 'bbox')).toBe(bounds)
 await page.goBack()
 await expect(aoi).toHaveValue('')
 await page.goForward()
 await expect(aoi).toHaveValue(bounds)
 await page.goBack()
 await expect(aoi).toHaveValue('')
 const bookmark = page.url()
 await page.reload()
 await expect(selected.getByRole('heading', { name: /aircraft.*claimed abcdef/ })).toBeVisible()
 expect(page.url()).toBe(bookmark)
 await page.screenshot({ path: '../../tmp/p24-p32/external-track-desktop.png' })
 await page.setViewportSize({ width: 390, height: 844 })
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
 await page.screenshot({ path: '../../tmp/p24-p32/external-track-mobile.png' })
 await selected.getByRole('link', { name: 'Inspect position on the Public Context map' }).click()
 await expect.poll(() => new URL(page.url()).searchParams.get('selected')).toBe(`track:${fixture.moving.id}`)
 await expect(page.getByRole('button', { name: 'Public Context', exact: true })).toHaveAttribute('aria-pressed','true')
})
