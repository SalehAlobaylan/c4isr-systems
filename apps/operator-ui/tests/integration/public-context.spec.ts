import {mapControl} from '../recovery/atlas-helpers'
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'

import { expect, test } from './test'

const fixture = JSON.parse(process.env.EMAD_BROWSER_FIXTURE ?? '{}')

async function openEvidence(page: import('@playwright/test').Page) {
  await mapControl(page,'Evidence inspector')
  await expect(page.getByLabel('Public event and reference data')).toBeVisible();await expect(page.getByRole('dialog')).toHaveCount(0)
}

test('real public report and frozen reference remain inspectable with exact originals', async ({ page }) => {
  await page.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.token)
  await page.goto(`${fixture.url}/map`)
  await page.getByRole('button', { name: 'Public Context', exact: true }).click()
  await openEvidence(page)
  await expect(page.getByText('Made with Natural Earth, v5.1.2, 1:50 million', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /^Reported browser earthquake · event\.earthquake/ }).click()
  const evidence = page.getByRole('region', { name: 'Reported event evidence' })
  await expect(evidence.getByText('Browser report fixture via Fixture provider', { exact: false })).toBeVisible()
  await evidence.getByText('Retained original provider record', { exact: true }).click()
  const response = page.waitForResponse((r) => r.url().endsWith('/original'))
  const download = page.waitForEvent('download')
  await evidence.getByRole('button', { name: 'Download exact original' }).click()
  const file = await download
  const bytes = await readFile((await file.path())!)
  const originalResponse = await response
  expect(originalResponse.status()).toBe(200)
  expect(bytes.toString()).toBe('{ "kind": "reported earthquake fixture", "magnitude": 3.5 }')
  const evidenceUrl = originalResponse.url().replace(/\/original$/, '')
  const detail = await page.request.get(evidenceUrl, { headers: { Authorization: `Bearer ${fixture.token}`, 'X-EMAD-Workspace-ID': fixture.public.workspaceId, 'X-EMAD-Environment-ID': fixture.public.environmentId, 'X-EMAD-Partition': 'PUBLIC_EVIDENCE' } })
  expect(createHash('sha256').update(bytes).digest('hex')).toBe((await detail.json()).rawHash)
  await page.getByLabel('Reference version').selectOption({ label: 'Jeddah/Makkah coarse elevation reference · 2022-v1-60s-subset-v1' })
  await expect(page.getByText('EGM2008 orthometric height, metres, positive up', { exact: false })).toBeVisible()
  await expect(page.getByText('Artifact SHA-256:', { exact: false }).first()).toBeVisible()
  await page.getByRole('button',{name:'Time & filters',exact:true}).click()
  await page.getByText('Filters and historical view', { exact: true }).click()
  const filters = page.getByLabel('Filter public evidence')
  await filters.getByLabel('Historical interpretation').selectOption('known_at')
  const cutoff = new Date(fixture.beforeReport)
  const localCutoff = new Date(cutoff.getTime() - cutoff.getTimezoneOffset() * 60_000).toISOString().slice(0, 16)
  await filters.getByLabel('As-of time (local)').fill(localCutoff)
  await filters.getByRole('button', { name: 'Apply public filters' }).click()
  await expect(page.getByLabel('Public view meaning')).toContainText('Later arrivals and publications are excluded')
  await openEvidence(page)
  await expect(page.getByText('No published reports in this bounded view.', { exact: false })).toBeVisible()
  await expect(page.getByLabel('Entity board overlay')).toHaveCount(0)
  await expect(page.getByLabel('Operations rail')).toHaveCount(0)
  const bookmark = page.url()
  await page.reload()
  await openEvidence(page)
  await expect(page.getByText('No published reports in this bounded view.', { exact: false })).toBeVisible()
  expect(page.url()).toBe(bookmark)
  await page.getByRole('button',{name:'Time & filters',exact:true}).click()
  await page.getByText('Filters and historical view', { exact: true }).click()
  await filters.getByLabel('Historical interpretation').selectOption('effective_at')
  await filters.getByRole('button', { name: 'Apply public filters' }).click()
  await expect(page.getByLabel('Public view meaning')).toContainText('Late arrivals may appear')
  await openEvidence(page)
  await expect(page.getByRole('button', { name: /^Reported browser earthquake ·/ })).toBeVisible()
  await expect(page.getByLabel('Historical report map')).toBeVisible()
  await expect(page.getByLabel('Entity board overlay')).toHaveCount(0)
  await expect(page.getByLabel('Operations rail')).toHaveCount(0)
  await expect(page.locator('[data-map-ready="true"]')).toBeVisible()
  await page.getByRole('button', { name: /^Reported browser earthquake ·/ }).click()
  await expect(page.getByRole('region', { name: 'Reported event evidence' })).toBeVisible()
  await page.screenshot({ path: '../../tmp/p16-real-history-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByLabel('Historical report map')).toBeVisible()
  await page.screenshot({ path: '../../tmp/p16-real-history-mobile.png', fullPage: true })
  await page.getByRole('button',{name:'Time & filters',exact:true}).click()
  await page.getByText('Filters and historical view', { exact: true }).click()
  await filters.getByRole('button', { name: 'Reset public filters' }).click()
  await expect(page.getByLabel('Public view meaning')).toContainText('Latest published')
})
