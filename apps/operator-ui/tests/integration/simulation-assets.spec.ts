import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { test, expect } from './test'
const fixture = JSON.parse(process.env.EMAD_BROWSER_FIXTURE ?? '{}')
test('protected asset import retains licensed geometry and separate authoring definitions',async({page})=>{
 await page.addInitScript((token)=>{window.__C4ISR_CONFIG__={apiToken:token}},fixture.token)
 await page.goto(`${fixture.url}/scenarios`)
 await page.getByRole('link',{name:'Simulation asset registry',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Asset library',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Import an asset',exact:true}).click()
 const admit=page.getByRole('region',{name:'Admit simulation asset'})
 await admit.getByLabel('Asset name',{exact:true}).fill('Synthetic portable wing')
 const bytes=await readFile('../../testdata/models/abstract-wing.glb')
 await admit.getByLabel('Asset file',{exact:true}).setInputFiles({name:'abstract-wing.glb',mimeType:'model/gltf-binary',buffer:bytes})
 await admit.getByLabel('Original source reference (HTTPS)').fill('https://example.invalid/emad-fixtures')
 await admit.getByLabel('Source and processing provenance',{exact:true}).fill('Project-authored synthetic fixture; not validated physical aircraft performance.')
 await admit.getByLabel('Reviewed license record / identifier').fill('LicenseRef-EMAD-TestFixture')
 await admit.getByLabel('License terms URL').fill('https://example.invalid/emad-fixtures')
 await admit.getByLabel('Required attribution').fill('EMAD synthetic model fixture')
 await admit.getByLabel('Legal basis and usage limitations').fill('Project-authored mesh for internal development and synthetic simulation; no external redistribution.')
 await admit.getByRole('checkbox',{name:'I reviewed the terms',exact:false}).check()
 await admit.getByRole('button',{name:'Retain and queue asset',exact:true}).click()
 await page.getByRole('button',{name:'Visual models',exact:true}).click()
 await page.getByRole('button',{name:'Inspect model Synthetic portable wing',exact:true}).click({timeout:30_000})
 const model=page.getByRole('article',{name:'Selected visual model'})
 await expect(model).toContainText('1 triangle')
 await expect(model).toContainText('visual only')
 await expect(model).toContainText('redistribution not permitted by this record')
 const download=page.waitForEvent('download')
 await model.getByRole('button',{name:'Download exact validation manifest'}).click()
 const raw=JSON.parse(await readFile((await(await download).path())!,'utf8'))
 expect(raw.importer).toBe('emad-static-gltf-v1');expect(raw.triangles).toBe(1)
 await page.getByRole('button',{name:'Close',exact:true}).click()
 await page.getByRole('button',{name:'Imports & validation',exact:true}).click()
 const sourceDownload=page.waitForEvent('download')
 await page.getByRole('button',{name:'Download source for Synthetic portable wing'}).click()
 const original=await readFile((await(await sourceDownload).path())!)
 expect(createHash('sha256').update(original).digest('hex')).toBe(createHash('sha256').update(bytes).digest('hex'))
 await page.getByRole('button',{name:'Visual models',exact:true}).click()
 await page.getByRole('button',{name:'Inspect model Synthetic portable wing',exact:true}).click()
 await page.getByText('Create an actor template from this model',{exact:true}).click()
 const template=model.getByRole('region',{name:'Actor template authoring'})
 await template.getByLabel('Template name',{exact:true}).fill('Synthetic static wing template')
 await template.getByLabel('Behavior limitations').fill('Static abstract fixture; no sensors or flight dynamics are implemented.')
 await template.getByRole('button',{name:'Record actor template'}).click()
 await page.getByRole('button',{name:'Close',exact:true}).click()
 await page.getByRole('button',{name:'Templates & environments',exact:true}).click()
 await expect(page.getByRole('region',{name:'Authored templates and environments'})).toContainText('Synthetic static wing template')
 await page.getByRole('button',{name:'Visual models',exact:true}).click()
 await page.getByRole('button',{name:'Inspect model Synthetic portable wing',exact:true}).click()
 await page.getByText('Register this model as a visual environment',{exact:true}).click()
 const env=model.getByRole('region',{name:'Environment asset authoring'})
 await env.getByLabel('Environment asset name').fill('Synthetic placed mesh')
 await env.getByLabel('Origin longitude').fill('39.2');await env.getByLabel('Origin latitude').fill('21.5');await env.getByLabel('Ellipsoidal height (metres)').fill('10')
 await env.getByLabel('Environment source and placement provenance').fill('Synthetic geometry at a declared local origin, not measured terrain.')
 await env.getByRole('button',{name:'Record environment asset'}).click()
 await page.getByRole('button',{name:'Close',exact:true}).click()
 await page.getByRole('button',{name:'Templates & environments',exact:true}).click()
 await expect(page.getByRole('region',{name:'Authored templates and environments'})).toContainText('Synthetic placed mesh')
 await page.getByRole('button',{name:'Visual models',exact:true}).click()
 await page.getByRole('button',{name:'Inspect model Synthetic portable wing',exact:true}).click()
 const bookmark=page.url();await page.reload();await expect(model).toContainText('Synthetic portable wing');expect(page.url()).toBe(bookmark)
 await page.screenshot({path:'../../tmp/s1-1/asset-registry-desktop.png'})
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await model.getByRole('heading',{name:'Synthetic portable wing · visual only'}).scrollIntoViewIfNeeded()
 await page.screenshot({path:'../../tmp/s1-1/asset-registry-mobile.png'})
 // Ordinary picture and public views still use their original partitions.
 await page.getByRole('button',{name:'Close',exact:true}).click()
 await page.getByRole('button',{name:'Public Context',exact:true}).click()
 await expect(page.getByRole('button',{name:'Public Context',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.goto(`${fixture.url}/simulation-assets`)
 await expect(page.getByRole('heading',{name:'Asset library',exact:true})).toBeVisible()
})
