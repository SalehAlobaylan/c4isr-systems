import { test,expect } from './test'
import {readFile} from 'node:fs/promises'
import {createHash} from 'node:crypto'
const fixture=JSON.parse(process.env.EMAD_BROWSER_FIXTURE??'{}')
test('Studio loads a pinned georeferenced scene, freezes placement edits and controls a separate native process',async({page})=>{
 await page.addInitScript(token=>{window.__C4ISR_CONFIG__={apiToken:token}},fixture.studio.token)
 await page.goto(`${fixture.url}/simulation-studio?scene=${fixture.studio.sceneId}`)
 await expect(page.getByRole('heading',{name:'Simulation Studio',exact:true})).toBeVisible()
 const viewport=page.getByRole('region',{name:'Georeferenced viewport'})
 await expect(viewport.locator('[data-render-ready]')).toHaveAttribute('data-render-ready','true')
 await expect(viewport).toContainText('3 authored actors')
 await page.getByText('Rights, provenance and fidelity',{exact:true}).click()
 await expect(page.getByRole('group',{name:'Scene rights and fidelity'})).toContainText('EMAD synthetic terrain fixture')
 await expect(page.getByRole('group',{name:'Scene rights and fidelity'})).toContainText('projected to the origin-height surface')
 await page.getByRole('region',{name:'Scene hierarchy'}).getByRole('button',{name:/^waypoint-a/}).click()
 await page.getByText('Scene setup & templates',{exact:true}).click()
 await page.getByLabel('Actor longitude',{exact:true}).fill('39.2015')
 await page.getByLabel('Scene name',{exact:true}).fill('Browser edited georeferenced scene')
 await page.getByRole('button',{name:'Freeze scene version',exact:true}).click()
 await expect(page).not.toHaveURL(new RegExp(fixture.studio.sceneId))
 await expect(viewport.locator('[data-render-ready]')).toHaveAttribute('data-render-ready','true')
 const bookmark=page.url();await page.reload();await expect(viewport.locator('[data-render-ready]')).toHaveAttribute('data-render-ready','true');expect(page.url()).toBe(bookmark)
 await page.getByText('Rights, provenance and fidelity',{exact:true}).click()
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download frozen scene',exact:true}).click()
 const exact=(await readFile((await(await download).path())!,'utf8')).trim(),frozen=exact.slice(exact.indexOf('"frozen":')+9,-1)
 expect('scene_'+createHash('sha256').update(frozen).digest('hex')).toBe(JSON.parse(exact).id)
 await page.getByRole('region',{name:'Scene hierarchy'}).getByRole('button',{name:/^waypoint-a/}).click();await viewport.getByRole('button',{name:'Focus selected actor',exact:true}).click()
 await expect(viewport.getByText('waypoint-a',{exact:true})).toBeVisible()
 await viewport.scrollIntoViewIfNeeded();await page.screenshot({path:'../../tmp/s1-s2/studio-actor-focus.png'})
 await viewport.getByRole('button',{name:'Reset scene view',exact:true}).click()
 await viewport.scrollIntoViewIfNeeded();await page.screenshot({path:'../../tmp/s1-s2/studio-desktop.png'})
 const runtime=page.getByRole('region',{name:'Native runtime control'})
 await expect(runtime.getByRole('button',{name:'Start exercise',exact:true})).toBeEnabled({timeout:15000})
 await runtime.getByRole('button',{name:'Start exercise',exact:true}).click()
 await expect(runtime).toContainText(/RUNNING · desired RUNNING/,{timeout:20000})
 await runtime.getByRole('button',{name:'Pause runtime',exact:true}).click();await expect(runtime).toContainText(/PAUSED · desired PAUSED/)
 await runtime.getByRole('button',{name:'Resume runtime',exact:true}).click();await expect(runtime).toContainText(/RUNNING · desired RUNNING/)
 await runtime.getByRole('button',{name:'Stop runtime',exact:true}).click();await expect(runtime).toContainText(/STOPPED · desired STOPPED/)
 await page.setViewportSize({width:390,height:844});await viewport.scrollIntoViewIfNeeded()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.screenshot({path:'../../tmp/s1-s2/studio-mobile.png'})
 await page.getByRole('button',{name:'2D overview',exact:true}).click();await expect(viewport).toHaveCount(0);await expect(page.getByRole('region',{name:'Geographic overview'})).toBeVisible()
})
test('input-only authors enter Studio without an ordinary COP subscription',async({page})=>{
 const sockets:string[]=[];page.on('websocket',socket=>sockets.push(socket.url()))
 await page.addInitScript(token=>{window.__C4ISR_CONFIG__={apiToken:token}},fixture.studio.inputToken)
 await page.goto(`${fixture.url}/simulation-studio?scene=${fixture.studio.sceneId}`)
 await expect(page.getByRole('heading',{name:'Simulation Studio',exact:true})).toBeVisible()
 await expect(page.getByRole('region',{name:'Georeferenced viewport'}).locator('[data-render-ready]')).toHaveAttribute('data-render-ready','true')
 await expect(page.getByRole('navigation',{name:'Workspace navigation'})).toBeVisible()
 await expect(page.getByRole('region',{name:'Native runtime control'})).toHaveCount(0)
 expect(sockets).toEqual([])
})
