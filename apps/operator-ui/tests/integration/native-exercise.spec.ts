import {interpolateSnapshots} from '../../src/components/map/displaySnapshots'
import type {FeatureCollection} from 'geojson'
import {test, expect} from './test'
const fixture=JSON.parse(process.env.EMAD_BROWSER_FIXTURE ?? '{}')

test('native perception exercise freezes sensing settings and drives run-scoped mission tasking', async ({page}) => {
  await page.addInitScript(token => {window.__C4ISR_CONFIG__={apiToken:token}}, fixture.studio.token)
  await page.goto(`${fixture.url}/simulation-studio?scene=${fixture.studio.perceptionSceneId}`)
  await expect(page.getByRole('heading', {name:'Simulation Studio',exact:true})).toBeVisible()
  await page.getByText('Scene setup & templates',{exact:true}).click()
 await page.getByText('Synthetic sensors & controlled actors',{exact:true}).click()
  await expect(page.getByLabel('Sample interval (ms)',{exact:true})).toHaveValue('1000')
  await expect(page.getByLabel('Exercise-controlled actor · waypoint-a',{exact:true})).toBeChecked()
  await page.getByLabel('Delivery delay (ms)',{exact:true}).fill('1500')
  await page.getByLabel('Scene name',{exact:true}).fill('Browser frozen perception exercise')
  await page.getByRole('button',{name:'Freeze scene version',exact:true}).click()
  await expect(page).not.toHaveURL(new RegExp(fixture.studio.perceptionSceneId))
  await page.reload()
  await page.getByText('Scene setup & templates',{exact:true}).click()
 await page.getByText('Synthetic sensors & controlled actors',{exact:true}).click()
  await expect(page.getByLabel('Delivery delay (ms)',{exact:true})).toHaveValue('1500')
  const runtime=page.getByRole('region',{name:'Native runtime control'})
  await expect(runtime.getByRole('button',{name:'Start exercise',exact:true})).toBeEnabled({timeout:15000})
  await runtime.getByRole('button',{name:'Start exercise',exact:true}).click()
  await expect(runtime).toContainText('RUNNING · desired RUNNING',{timeout:20000})
  const studioURL=page.url()
  await runtime.getByRole('button',{name:'Open Exercise COP tasking',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Exercise operations',exact:true})).toBeVisible()
  const clock=page.getByRole('region',{name:'Exercise clock'})
  await expect(clock).toContainText('RUNNING')
  await expect(page.getByRole('region',{name:'Controlled virtual recipients'})).toContainText('TRAINER-01')
  await page.getByRole('combobox',{name:'Virtual recipient',exact:true}).selectOption({label:'TRAINER-01'})
  await page.getByLabel('New exercise mission name',{exact:true}).fill('Browser native mission')
  await page.getByRole('button',{name:'Create exercise mission',exact:true}).click()
  await expect(page.getByRole('combobox',{name:'Mission',exact:true})).toContainText('Browser native mission')
  await page.getByRole('button',{name:'Issue exercise command',exact:true}).click()
  const outcomes=page.getByRole('region',{name:'Exercise command outcomes'})
  await expect(outcomes).toContainText('HOLD · COMPLETED',{timeout:20000})
  await expect(page.getByRole('region',{name:'Exercise mission outcomes'})).toContainText('Complete virtual asset tasking · COMPLETED')
  await page.getByRole('combobox',{name:'Mission',exact:true}).selectOption('')
  await page.getByRole('combobox',{name:'Exercise action',exact:true}).selectOption('RESUME_ROUTE')
  await page.getByRole('button',{name:'Issue exercise command',exact:true}).click()
  await expect(outcomes).toContainText('RESUME_ROUTE · COMPLETED',{timeout:20000})
  const operationURL=page.url()
  await page.setViewportSize({width:390,height:844})
  await clock.scrollIntoViewIfNeeded()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'../../tmp/s2-s3/exercise-mobile.png'})
  await page.setViewportSize({width:1440,height:1000})
  await page.screenshot({path:'../../tmp/s2-s3/exercise-desktop.png'})
  await page.getByRole('link',{name:'Exercise COP',exact:true}).click()
  await expect(page.locator('[data-od-id="run-bar"]')).toContainText('Native exercise · RUNNING')
  await expect(page.locator('[data-od-id="run-bar"]')).toContainText('virtual')
  const mapText=await page.locator('body').innerText()
  for(const secret of ['waypoint-a','marker-a','private-observer']) expect(mapText).not.toContain(secret)
  await page.goto(studioURL)
  await page.getByRole('button',{name:'Stop runtime',exact:true}).click()
  await expect(page.getByRole('region',{name:'Native runtime control'})).toContainText('STOPPED · desired STOPPED')
  await page.goto(operationURL)
  await expect(page.getByRole('region',{name:'Exercise clock'})).toContainText('STOPPED')
  await expect(page.getByRole('button',{name:'Issue exercise command',exact:true})).toBeDisabled()
})

test('display smoothing uses only accepted positions and never mutates source snapshots', () => {
 const from:FeatureCollection={type:'FeatureCollection',features:[{type:'Feature',properties:{id:'contact-opaque'},geometry:{type:'Point',coordinates:[179.99,21]}}]}
 const to:FeatureCollection={type:'FeatureCollection',features:[{type:'Feature',properties:{id:'contact-opaque'},geometry:{type:'Point',coordinates:[-179.99,22]}}]}
 const before=JSON.stringify([from,to]),mid=interpolateSnapshots(from,to,.5).features[0].geometry
 expect(mid.type).toBe('Point')
 if(mid.type==='Point'){expect(Math.abs(mid.coordinates[0])).toBeCloseTo(180);expect(mid.coordinates[1]).toBe(21.5)}
 expect(interpolateSnapshots(from,to,2)).toEqual(interpolateSnapshots(from,to,1))
 expect(JSON.stringify([from,to])).toBe(before)
 expect(interpolateSnapshots(from,{type:'FeatureCollection',features:[]},.5).features).toEqual([])
})
