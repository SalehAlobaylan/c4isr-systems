test('explicit evaluator reads defined metrics and releases only selected numeric results',async({page})=>{
 await page.addInitScript(token=>{window.__C4ISR_CONFIG__={apiToken:token}},fixture.studio.evaluatorToken)
 await page.goto(`${fixture.url}/recordings?run=${fixture.studio.recordingId}&ms=6000&sequence=0`)
 await page.getByRole('button',{name:'Privileged evaluation',exact:true}).click()
 await page.getByRole('button',{name:'Open privileged evaluation',exact:true}).click()
 const panel=page.getByRole('region',{name:'Privileged after-action evaluation'})
 await expect(panel).toContainText('emad.abstract-evaluation.v2')
 await panel.getByText(/Evaluation metrics ·/).evaluate(e=>{(e.parentElement as HTMLDetailsElement).open=true})
 await expect(panel.getByRole('term').filter({hasText:'missed observations'})).toBeVisible()
 await expect(panel.getByRole('term').filter({hasText:'late observations'}).locator('..')).toContainText('sample count 9')
 await panel.getByText('Release selected numeric metrics to exercise operators',{exact:true}).click()
 await panel.getByRole('checkbox',{name:'scenario completed',exact:true}).check()
 await panel.getByLabel('Release reason',{exact:true}).fill('Approved browser exercise completion metric')
 await panel.getByRole('button',{name:'Release numeric summary',exact:true}).click()
 await expect(page.getByRole('region',{name:'Released operator report'})).toContainText('100.0%')
 await page.setViewportSize({width:390,height:844})
 await panel.scrollIntoViewIfNeeded()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'../../tmp/plan-review/evaluation-mobile.png'})
})

test('sensor-quality presets save, reapply and pin exact settings in frozen scene versions',async({page})=>{
 await page.addInitScript(token=>{window.__C4ISR_CONFIG__={apiToken:token}},fixture.studio.token)
 await page.goto(`${fixture.url}/simulation-studio?scene=${fixture.studio.perceptionSceneId}`)
 await page.getByText('Scene setup & templates',{exact:true}).click()
 await page.getByText('Synthetic sensors & controlled actors',{exact:true}).click()
 await page.getByText('Save first observer as a reusable quality preset',{exact:true}).click()
 await page.getByLabel('Preset name',{exact:true}).fill('Browser delayed observer')
 await page.getByRole('button',{name:'Save quality preset',exact:true}).click()
 await expect(page.getByText('Saved preset Browser delayed observer',{exact:true})).toBeVisible()
 await page.getByLabel('Delivery delay (ms)',{exact:true}).fill('3000')
 await page.getByRole('combobox',{name:'Quality preset for private-observer',exact:true}).selectOption({label:'Browser delayed observer'})
 await expect(page.getByLabel('Delivery delay (ms)',{exact:true})).toHaveValue('1000')
 await page.getByLabel('Scene name',{exact:true}).fill('Browser preset-pinned scene')
 await page.getByRole('button',{name:'Freeze scene version',exact:true}).click()
 await expect(page).not.toHaveURL(new RegExp(fixture.studio.perceptionSceneId))
 await page.reload()
 await page.getByText('Scene setup & templates',{exact:true}).click()
 await page.getByText('Synthetic sensors & controlled actors',{exact:true}).click()
 await expect(page.getByRole('combobox',{name:'Quality preset for private-observer',exact:true})).toHaveValue(/sensor_preset_/)
 await page.getByLabel('Delivery delay (ms)',{exact:true}).fill('2000')
 await expect(page.getByRole('combobox',{name:'Quality preset for private-observer',exact:true})).toHaveValue('')
})
