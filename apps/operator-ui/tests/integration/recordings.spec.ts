import {test,expect} from './test'
const fixture=JSON.parse(process.env.EMAD_BROWSER_FIXTURE??'{}')

test('recorded replay is historical, scoped, readable on mobile, and protects evaluator data',async({page})=>{
 await page.addInitScript(token=>{window.__C4ISR_CONFIG__={apiToken:token}},fixture.studio.token)
 const url=`${fixture.url}/recordings?run=${fixture.studio.recordingId}&ms=0&sequence=0`
 await page.goto(url)
 await expect(page.getByRole('heading',{name:'Exercise replay',exact:true})).toBeVisible()
 await expect(page.getByTestId('workspace-basis')).toHaveText('Recorded exercise output · virtual replay clock · read only')
 await expect(page.getByRole('group',{name:'Recording status'})).toContainText('READY · COMPLETED')
 await expect(page.getByRole('group',{name:'Recording status'})).toContainText('Archive attempts: 1 / 3')
 await page.locator('summary').filter({hasText:'Archive status & recovery'}).evaluate(e=>{(e.parentElement as HTMLDetailsElement).open=true})
 await expect(page.getByRole('button',{name:'Archive closed run',exact:true})).toBeDisabled()
 await page.getByText('Recorded contacts, assets & task outcomes',{exact:true}).click()
 const state=page.getByRole('region',{name:'Recorded state'})
 await expect(state).toContainText('observations · 0')
 await page.getByRole('button',{name:'Final frame',exact:true}).click()
 await expect(state).not.toContainText('observations · 0')
 await page.getByText('Recorded geographic coordinate overview',{exact:true}).click()
 await expect(page.getByRole('img',{name:/recorded contact and asset positions/})).toBeVisible()
 const finalURL=page.url()
 await page.reload()
 await expect(page.getByRole('group',{name:'Recording status'})).toContainText('virtual time 6.00 s')
 expect(page.url()).toBe(finalURL)
 for(const secret of ['waypoint-a','marker-a','private-observer','runtimeBuild','sensor_preset_'])expect(await page.locator('body').innerText()).not.toContain(secret)
 await page.getByRole('button',{name:'Privileged evaluation',exact:true}).click()
 await page.getByRole('button',{name:'Open privileged evaluation',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('explicit truth and evaluator grants')
 await page.getByRole('button',{name:'Close privileged evaluation',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('group',{name:'Recording status'}).scrollIntoViewIfNeeded()
 const header=page.locator('.workspace-header')
 await header.locator('summary').filter({hasText:'Account'}).click()
 const account=page.getByLabel('Account credential',{exact:true}),bounds=await account.boundingBox()
 expect(bounds).not.toBeNull();expect(bounds!.x).toBeGreaterThanOrEqual(0);expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(390)
 await header.locator('summary').filter({hasText:'Account'}).click()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'../../tmp/plan-review/replay-mobile.png'})
 await page.setViewportSize({width:1440,height:1000})
 await page.screenshot({path:'../../tmp/plan-review/replay-desktop.png'})
})

