import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { test, expect, workspaceSelection } from './test'

const fixture = JSON.parse(process.env.EMAD_BROWSER_FIXTURE ?? '{}')
test('real retained imagery comparison produces a traceable independently reviewed assessment', async ({ page, browser }) => {
  await page.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.token)
  await page.goto(`${fixture.url}/map`)
  await page.getByRole('button', { name: 'Public Context', exact: true }).click()
  await page.getByRole('navigation',{name:'Workspace navigation'}).getByRole('link',{name:'Imagery',exact:true}).click()
  await page.getByRole('navigation',{name:'Intelligence workspaces'}).getByRole('link',{name:'Scene catalogue',exact:true}).click()
  await expect(page.getByRole('heading', { name: 'Imagery intelligence', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Scene catalogue' }).getByRole('article')).toHaveCount(2)
  const headers = { Authorization: `Bearer ${fixture.token}`, 'X-EMAD-Workspace-ID': fixture.public.workspaceId, 'X-EMAD-Environment-ID': fixture.public.environmentId, 'X-EMAD-Partition': 'PUBLIC_EVIDENCE' }
  // Exercise the browser's binary upload path using an exact, explicitly
  // synthetic fixture subset that is already retained in this disposable setup.
  const preparedResponse = await page.request.get(`${fixture.url}/api/v1/imagery/jobs/${fixture.imagery.before}`, { headers })
  expect(preparedResponse.status()).toBe(200)
  const preparation = await preparedResponse.json()
  const subsetResponse = await page.request.get(`${fixture.url}/api/v1/artifacts/${preparation.input.artifacts[0].id}/content`, { headers })
  expect(subsetResponse.status()).toBe(200)
  await page.getByText('Retain and validate a prepared scene subset', { exact: true }).click()
  await page.getByRole('combobox', { name: 'Scene revision', exact: true }).selectOption(preparation.input.scenes[0].id)
  await page.getByLabel('Prepared subset JSON').setInputFiles({ name: 'synthetic-subset.json', mimeType: 'application/json', buffer: await subsetResponse.body() })
  await page.getByRole('button', { name: 'Upload and validate subset' }).click()
  await expect(page.getByRole('region', { name: 'Selected imagery job' }).getByRole('heading', { name: 'PREPARE · SUCCEEDED' })).toBeVisible({ timeout: 30_000 })
  await page.getByLabel('Before prepared subset').selectOption(fixture.imagery.before)
  await page.getByLabel('After prepared subset').selectOption(fixture.imagery.after)
  await page.getByRole('button', { name: 'Queue comparison', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Selected imagery job' }).getByRole('heading', { name: 'NDVI_CHANGE · SUCCEEDED' })).toBeVisible({ timeout: 30_000 })
  const comparison = page.getByRole('region', { name: 'Aligned NDVI comparison' })
  await expect(comparison.getByRole('status').filter({hasText:'SYNTHETIC FIXTURE'})).toContainText('these pixels are not observed environmental evidence')
  await expect(comparison.getByText('15 common clear cells', { exact: false })).toBeVisible()
  await expect(comparison.locator('canvas[aria-hidden=true]')).toHaveCount(3)
  await comparison.getByLabel('Inspect cell index (zero-based)').fill('0')
  await expect(comparison.getByText('Cell 0', { exact: false })).toContainText('difference: -0.500000')
  await comparison.getByLabel('Inspect NDVI difference cells; arrow keys move the selected cell').focus()
  await page.keyboard.press('ArrowRight')
  await expect(comparison.getByLabel('Inspect cell index (zero-based)')).toHaveValue('1')
  const bookmark = page.url()
  await page.reload()
  await expect(page.getByRole('region', { name: 'Aligned NDVI comparison' })).toBeVisible()
  expect(page.url()).toBe(bookmark)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download exact analysis result' }).click()
  const bytes = await readFile((await (await download).path())!)
  const result = JSON.parse(bytes.toString())
  expect(result.algorithm).toBe('emad.ndvi-change.v1')
  expect(result.synthetic).toBe(true)
  const jobID = workspaceSelection(page.url(), 'job')
  expect(jobID).toBeTruthy()
  const job = await (await page.request.get(`${fixture.url}/api/v1/imagery/jobs/${jobID}`, { headers })).json()
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(job.result.sha256)
  await page.getByLabel('Assessment conclusion').fill('Synthetic subset NDVI declined in three clear cells. This is not observed vegetation loss.')
  await page.getByLabel('Proposal method').selectOption('AI')
  await page.getByLabel('Model score (optional; not analyst confidence)').fill('0.9')
  await page.getByRole('button', { name: 'Record unreviewed proposal' }).click()
  const assessment = page.getByRole('article', { name: 'Selected assessment review' })
  await expect(assessment.getByRole('heading', { name: 'PROPOSED · revision 1' })).toBeVisible()
  await expect(assessment.getByText('model score: 0.9', { exact: false })).toContainText('analyst confidence: Not assigned')
  await expect(assessment.getByRole('button', { name: 'Begin independent review' })).toHaveCount(0)
  const assessmentID = workspaceSelection(page.url(), 'assessment')
  const reviewer = await browser.newPage()
  const failures: string[] = []
  reviewer.on('response', (r) => { if (r.status() >= 500 && new URL(r.url()).pathname.startsWith('/api/')) failures.push(`${r.status()} ${r.url()}`) })
  await reviewer.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.imagery.reviewerToken)
  try {
    await reviewer.goto(`${fixture.url}/intelligence?assessment=${assessmentID}`)
    const review = reviewer.getByRole('article', { name: 'Selected assessment review' })
    await expect(review.getByRole('heading', { name: 'PROPOSED · revision 1' })).toBeVisible()
    await review.getByLabel('Review rationale').fill('Reproduced the exact retained subset calculation; checked masks and synthetic provenance.')
    await review.getByRole('button', { name: 'Begin independent review' }).click()
    await expect(review.getByRole('heading', { name: 'IN_REVIEW · revision 2' })).toBeVisible()
    await review.getByLabel('Analyst confidence for publication').fill('0.6')
    await review.getByLabel('Analyst confidence rationale').fill('Calculation verified, with explicit synthetic fixture and noncausal interpretation limitations.')
    await review.getByRole('button', { name: 'Publish reviewed assessment' }).click()
    await expect(review.getByRole('heading', { name: 'PUBLISHED · revision 3' })).toBeVisible()
    await expect(review.getByText('model score: 0.9', { exact: false })).toContainText('analyst confidence: 0.6')
    await review.getByText('Registered identities & audit principals',{exact:true}).click()
    await expect(review.getByText('published by browser-independent-reviewer', { exact: false })).toBeVisible()
    await review.getByRole('button', { name: 'Inspect exact supporting comparison' }).click()
    await expect(reviewer.getByRole('region', { name: 'Aligned NDVI comparison' })).toBeVisible()
    await reviewer.setViewportSize({ width: 1440, height: 1000 })
    await reviewer.getByRole('region', { name: 'Aligned NDVI comparison' }).screenshot({ path: '../../tmp/p2/intelligence-comparison.png' })
    await reviewer.screenshot({ path: '../../tmp/p2/intelligence-desktop.png', fullPage: true })
    await reviewer.setViewportSize({ width: 390, height: 844 })
    await expect(reviewer.getByLabel('Before prepared subset')).toBeVisible()
    expect(await reviewer.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await reviewer.getByRole('navigation',{name:'Intelligence workspaces'}).getByRole('link',{name:'Assessment review',exact:true}).click()
    await review.scrollIntoViewIfNeeded()
    await reviewer.screenshot({ path: '../../tmp/p2/intelligence-mobile.png', fullPage: true })
    expect(failures).toEqual([])
  } finally { await reviewer.close() }
  await page.reload()
  await page.getByRole('navigation',{name:'Intelligence workspaces'}).getByRole('link',{name:'Context packages',exact:true}).click()
  const exporter = page.getByRole('region', { name: 'Approved context export' })
  await expect(exporter.getByLabel('Include selected published assessment', { exact: false })).toBeVisible()
  await exporter.getByLabel('Export AOI (west,south,east,north)').fill('39.1601,21.4893,39.1607,21.4899')
  await exporter.getByLabel('Export interval from (UTC)').fill('2025-02-01T00:00')
  await exporter.getByLabel('Export interval to (UTC)').fill('2025-02-28T23:59')
  await exporter.getByLabel('Accepted accuracy and imagery limitations').fill('Synthetic angular subsets with masks; no assertion of observed vegetation loss.')
  await exporter.getByRole('button', { name: 'Preview selected context', exact: true }).click()
  const preview = exporter.getByRole('region', { name: 'Context export preview' })
  await expect(preview.getByRole('article')).toHaveCount(5)
  await expect(preview.getByText('SYNTHETIC / DERIVED CONTEXT', { exact: false })).toBeVisible()
  await expect(preview.getByRole('button', { name: 'Approve and freeze this preview' })).toBeDisabled()
  await preview.getByLabel('Human approval statement').fill('Approve this exact reviewed synthetic context with the declared limitations.')
  await preview.getByRole('button', { name: 'Approve and freeze this preview' }).click()
  await expect(exporter.getByRole('status')).toContainText('Frozen context ctx_')
  const contextDownload = page.waitForEvent('download')
  await exporter.getByRole('button', { name: 'Download approved offline bundle' }).click()
  const bundle = JSON.parse(await readFile((await (await contextDownload).path())!, 'utf8'))
  await mkdir('../../tmp/p24-p32', { recursive: true })
  await writeFile('../../tmp/p24-p32/approved-context.json', JSON.stringify(bundle))
  expect(bundle.manifest.processingVersion).toBe('context-snapshot-v2')
  expect(bundle.manifest.reproduction).toBe('retained_offline')
  expect(bundle.manifest.assets).toHaveLength(5)
  for (const asset of bundle.manifest.assets) expect(createHash('sha256').update(Buffer.from(bundle.assets[asset.sha256], 'base64')).digest('hex')).toBe(asset.sha256)
  await exporter.getByRole('heading', { name: 'Build a reusable context package' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../../tmp/p24-p32/context-export-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(preview.getByLabel('Human approval statement')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await exporter.getByRole('heading', { name: 'Build a reusable context package' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../../tmp/p24-p32/context-export-mobile.png' })
})

test('imagery distinguishes an empty AOI, invalid filter and unavailable job', async ({ page }) => {
  await page.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.imagery.reviewerToken)
  await page.goto(`${fixture.url}/intelligence?view=catalogue&bbox=0,0,0.1,0.1`)
  await expect(page.getByText('No scene revisions in this bounded view.', { exact: true })).toBeVisible()
  await page.getByLabel('Scene AOI (west,south,east,north)').fill('invalid')
  await page.getByRole('button', { name: 'Filter scenes' }).click()
  await expect(page.getByRole('alert')).toContainText('Some authorized imagery records are unavailable')
  await page.getByLabel('Scene AOI (west,south,east,north)').fill('39.15,21.45,39.2,21.5')
  await page.getByRole('button', { name: 'Filter scenes' }).click()
  await expect(page.getByRole('region', { name: 'Scene catalogue' }).getByRole('article')).toHaveCount(2)
  await page.goto(`${fixture.url}/intelligence?job=unavailable-fixture-job`)
  await expect(page.getByText('The selected job is unavailable in this workspace.', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Aligned NDVI comparison' })).toHaveCount(0)
})
