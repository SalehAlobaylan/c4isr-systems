import { readFile } from 'node:fs/promises'
import { test, expect, workspaceSelection } from './test'
const fixture = JSON.parse(process.env.EMAD_BROWSER_FIXTURE ?? '{}')
test('station context and official claims retain provenance through independent review', async ({ page, browser }) => {
  await page.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.token)
  await page.goto(`${fixture.url}/map`)
  await page.getByRole('button', { name: 'Public Context', exact: true }).click()
  await page.getByRole('navigation',{name:'Workspace navigation'}).getByRole('link',{name:'Systems',exact:true}).click()
  await page.getByRole('link',{name:'Open weather & reports →',exact:true}).click()
  await expect(page.getByRole('heading', { name: 'Weather & official reports', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /OEJN station weather/ }).click()
  const selected = page.getByRole('article', { name: 'Pinned context evidence' })
  await expect(selected.getByRole('region', { name: 'Station weather sample' })).toContainText('Temperature: 0 °C')
  await expect(selected).toContainText('Variable; no fixed bearing')
  await expect(selected).toContainText('At least 10 statute miles')
  await expect(selected).toContainText('dewpoint: Unknown')
  await selected.getByText('Retained samples and revisions',{exact:true}).click()
  await expect(selected.getByRole('button', { name: /Inspect cited/ })).toHaveCount(2)
  const download = page.waitForEvent('download')
  await selected.getByRole('button', { name: 'Download exact provider record' }).click()
  const raw = JSON.parse(await readFile((await (await download).path())!, 'utf8'))
  expect(raw.rawOb).toBe('SYNTHETIC OEJN VARIABLE WIND SAMPLE')
  await page.screenshot({ path: '../../tmp/p3-3/weather-desktop.png' })
  await page.getByRole('button', { name: /Synthetic official earthquake bulletin.*REPORT/ }).click()
  await expect(selected.getByRole('region', { name: 'Provider report claim' })).toContainText('upstream:usgs-neic')
  await expect(selected).toContainText('Automatic provider bulletin, not an expert-reviewed assessment')
  const bookmark = page.url()
  await page.reload()
  await expect(selected.getByRole('heading', { name: 'Synthetic official earthquake bulletin', exact: true })).toBeVisible()
  expect(page.url()).toBe(bookmark)
  const reportDownload = page.waitForEvent('download')
  await selected.getByRole('button', { name: 'Download exact provider record' }).click()
  const sourceReport = JSON.parse(await readFile((await (await reportDownload).path())!, 'utf8'))
  expect(sourceReport.properties.source).toBe('NEIC')
  expect(sourceReport.properties.description).toContain('revision 2')
  await page.getByLabel('Report assessment conclusion').fill('Synthetic provider report shares NEIC lineage and does not establish verified impacts.')
  await page.getByRole('button', { name: 'Record unreviewed report proposal', exact: true }).click()
  const assessment = page.getByRole('article', { name: 'Selected report assessment' })
  await expect(assessment.getByRole('heading', { name: 'PROPOSED · revision 1' })).toBeVisible()
  await expect(assessment.getByRole('button', { name: 'Begin report review' })).toHaveCount(0)
  const assessmentId = workspaceSelection(page.url(), 'assessment')
  const reviewer = await browser.newPage()
  await reviewer.addInitScript((token) => { window.__C4ISR_CONFIG__ = { apiToken: token } }, fixture.context.reviewerToken)
  try {
    await reviewer.goto(`${fixture.url}/weather-reports?assessment=${assessmentId}&id=${fixture.context.reportId}`)
    const review = reviewer.getByRole('article', { name: 'Selected report assessment' })
    await review.getByLabel('Report review rationale').fill('Reviewed exact synthetic report, cited uncertainty and common NEIC source.')
    await review.getByRole('button', { name: 'Begin report review', exact: true }).click()
    await expect(review.getByRole('heading', { name: 'IN_REVIEW · revision 2' })).toBeVisible()
    await review.getByLabel('Report analyst confidence', { exact: true }).fill('0.5')
    await review.getByLabel('Report confidence rationale', { exact: true }).fill('One upstream source; no independent confirmation of impacts.')
    await review.getByRole('button', { name: 'Publish reviewed report assessment' }).click()
    await expect(review.getByRole('heading', { name: 'PUBLISHED · revision 3' })).toBeVisible()
    await expect(review).toContainText('analyst confidence: 0.5')
    await review.getByRole('button', { name: 'Inspect pinned report evidence' }).click()
    await expect(reviewer.getByRole('article', { name: 'Pinned context evidence' })).toContainText('Synthetic provider claim revision 2')
    await reviewer.screenshot({ path: '../../tmp/p3-3/report-review-desktop.png' })
  } finally { await reviewer.close() }
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../../tmp/p3-3/report-mobile.png' })
})
