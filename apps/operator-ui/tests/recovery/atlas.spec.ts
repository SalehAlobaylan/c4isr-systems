test('new retained revisions are flagged without recentering the map or relabeling observation time',async({page})=>{
 // This response-only browser fixture never writes an observation or an
 // assessment into the persistent installation.
 let deliverRevision=false
 await page.route('**/api/v1/map/features?*',async route=>{
  if(new URL(route.request().url()).searchParams.get('family')!=='earthquakes'){await route.continue();return}
  const response=await route.fetch(),body=await response.json()
  if(deliverRevision&&body.features.length){const f=body.features[0];f.id+='_browser_revision';f.properties={...f.properties,recordId:f.id,title:'Browser-only retained revision fixture'}}
  await route.fulfill({response,json:body})
 })
 await openMap(page);await page.getByLabel('Show area situation',{exact:true}).click();await expect(page.getByLabel('Area situation',{exact:true}).getByRole('button').filter({hasText:'Earthquake reports'})).toContainText('16');const before=await camera(page)
 deliverRevision=true
 await page.getByRole('button',{name:'Refresh display',exact:true}).click()
 const updates=page.getByRole('button',{name:/1 new \/ revised retained records/})
 await page.getByLabel('Show area situation',{exact:true}).click();await expect(updates).toBeVisible()
 await expect(updates).toHaveAttribute('title',/historical evidence/)
 expect(await camera(page)).toBe(before)
})
